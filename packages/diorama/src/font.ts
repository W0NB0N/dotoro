/** Stylized blocks that read as dense city signage without saying anything. */
const NOISE_GLYPHS: readonly (readonly string[])[] = [
  ['#####', '#.#.#', '#####', '#.#.#', '#####', '..#..', '#####'],
  ['..#..', '#####', '#...#', '#####', '#...#', '#####', '#...#'],
  ['#.#.#', '#.#.#', '#####', '..#..', '#####', '#.#.#', '#.#.#'],
  ['#####', '..#..', '.###.', '#.#.#', '..#..', '#####', '..#..'],
  ['#..##', '####.', '#..#.', '####.', '#..#.', '##.##', '#..##'],
  ['.#.#.', '#####', '.#.#.', '#####', '.#.#.', '.#.#.', '##.##'],
];

const glyphRows = (ch: string): readonly string[] => GLYPHS[ch] ?? GLYPHS[' ']!;

export const textWidth = (str: string, size = 1, gap = 1) => [...str].length * (5 + gap) * size - gap * size;

export type PlotPixel = (x: number, y: number) => void;

function plotRows(plot: PlotPixel, rows: readonly string[], x: number, y: number, size: number) {
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      if (row[i] !== '#') continue;
      for (let v = 0; v < size; v++) for (let u = 0; u < size; u++) plot(x + i * size + u, y + j * size + v);
    }
  });
}

export function text(c: Canvas, str: string, x: number, y: number, color: RGB, size = 1, gap = 1) {
  plotText((px, py) => c.set(px, py, color), str, x, y, size, gap);
}

export function plotText(plot: PlotPixel, str: string, x: number, y: number, size = 1, gap = 1) {
  let cx = x;
  for (const ch of str) {
    plotRows(plot, glyphRows(ch), cx, y, size);
    cx += (5 + gap) * size;
  }
}

export function plotNoiseGlyph(plot: PlotPixel, index: number, x: number, y: number, size = 1) {
  plotRows(plot, NOISE_GLYPHS[index % NOISE_GLYPHS.length]!, x, y, size);
}

/** Raw glyph access for effects that sample text themselves, like scrolling tickers. */
export function textMask(str: string, gap = 2): { w: number; on: (x: number, y: number) => boolean } {
  const glyphs = [...str].map(glyphRows);
  const cell = 5 + gap;
  return {
    w: glyphs.length * cell,
    on(x, y) {
      const g = glyphs[Math.floor(x / cell)];
      const col = x % cell;
      return !!g && col < 5 && g[y]?.[col] === '#';
    },
  };
}

